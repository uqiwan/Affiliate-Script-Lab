# Skrip Pembangun Otomatis APK Android Gagaswara Teleprompter
# Mendukung macOS, Linux, dan CI/CD tanpa error path, izin, missing GradleWrapperMain, atau SDK location not found.
#

set -e

# 0. Dapatkan lokasi absolut dari direktori skrip (bekerja di macOS & Linux)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$SCRIPT_DIR"
ANDROID_DIR="$ROOT_DIR/android"
WRAPPER_DIR="$ANDROID_DIR/gradle/wrapper"
WRAPPER_JAR="$WRAPPER_DIR/gradle-wrapper.jar"
TEMPLATE_JAR="$ROOT_DIR/scripts/android-templates/gradle-wrapper.jar"
LOCAL_PROPS="$ANDROID_DIR/local.properties"

cd "$ROOT_DIR"

echo "=========================================================="
echo "🚀 Membangun Gagaswara Teleprompter Android APK"
echo "Direktori Proyek: $ROOT_DIR"
echo "=========================================================="

# 1. Build frontend web production bundle
echo "📦 Langkah 1/4: Membangun bundle web..."
npm run build

# 2. Sinkronisasi aset web ke proyek Android
echo "🔄 Langkah 2/4: Menyinkronkan ke platform Capacitor Android..."
if [ ! -d "$ANDROID_DIR" ]; then
    echo "Direktori android belum ditemukan. Menjalankan npx cap add android..."
    npx cap add android
else
    npx cap sync android
fi

# 3. Integrasi & patch komponen native Android (FloatingPrompterService, Bridge, Manifest, gradlew, local.properties)
echo "🛡️  Langkah 3/4: Memverifikasi & mengintegrasikan layanan Floating Prompter native..."
node "$ROOT_DIR/scripts/patch-android.js"

# 4. Deteksi Otomatis & Konfigurasi Android SDK (Mengatasi 'SDK location not found')
echo "🔍 Memeriksa konfigurasi Android SDK & local.properties..."
DETECTED_SDK=""

# A. Periksa apakah sudah ada di local.properties yang valid
if [ -f "$LOCAL_PROPS" ]; then
    EXISTING_SDK=$(grep -E "^sdk\.dir=" "$LOCAL_PROPS" | cut -d'=' -f2- | tr -d '\r' || true)
    if [ -n "$EXISTING_SDK" ] && [ -d "$EXISTING_SDK" ]; then
        DETECTED_SDK="$EXISTING_SDK"
    fi
fi

# B. Jika belum ditemukan, periksa environment variable dan lokasi standar sistem operasi
if [ -z "$DETECTED_SDK" ]; then
    CANDIDATES=(
        "$ANDROID_HOME"
        "$ANDROID_SDK_ROOT"
        "$HOME/Library/Android/sdk"
        "/Users/$(whoami 2>/dev/null || echo "")/Library/Android/sdk"
        "$HOME/Android/Sdk"
        "/opt/homebrew/share/android-commandlinetools"
        "/usr/local/share/android-sdk"
        "$LOCALAPPDATA/Android/Sdk"
    )

    for CANDIDATE in "${CANDIDATES[@]}"; do
        if [ -n "$CANDIDATE" ] && [ -d "$CANDIDATE" ]; then
            DETECTED_SDK="$CANDIDATE"
            break
        fi
    done
fi

# C. Tulis atau perbarui local.properties jika SDK ditemukan
if [ -n "$DETECTED_SDK" ]; then
    export ANDROID_HOME="$DETECTED_SDK"
    export ANDROID_SDK_ROOT="$DETECTED_SDK"
    export PATH="$DETECTED_SDK/platform-tools:$DETECTED_SDK/cmdline-tools/latest/bin:$PATH"
    
    mkdir -p "$ANDROID_DIR"
    echo "## Auto-generated by build-apk.sh" > "$LOCAL_PROPS"
    echo "sdk.dir=$DETECTED_SDK" >> "$LOCAL_PROPS"
    echo "✅ Android SDK terdeteksi otomatis: $DETECTED_SDK"
    echo "✅ File android/local.properties berhasil disiapkan."
else
    echo "⚠️  Catatan: Android SDK belum terdeteksi di lokasi standar ($HOME/Library/Android/sdk)."
fi

# 5. Verifikasi dan pemulihan otomatis Gradle Wrapper (gradle-wrapper.jar)
mkdir -p "$WRAPPER_DIR"

if [ ! -f "$WRAPPER_JAR" ] || [ ! -s "$WRAPPER_JAR" ]; then
    echo "⚠️  File gradle-wrapper.jar tidak ditemukan atau kosong. Memulihkan wrapper..."

    # Opsi A: Salin dari cadangan template lokal jika tersedia
    if [ -f "$TEMPLATE_JAR" ] && [ -s "$TEMPLATE_JAR" ]; then
        echo "✅ Menyalin gradle-wrapper.jar dari cadangan template..."
        cp "$TEMPLATE_JAR" "$WRAPPER_JAR"

    # Opsi B: Buat wrapper resmi menggunakan 'gradle wrapper' jika gradle terpasang
    elif command -v gradle >/dev/null 2>&1; then
        echo "✅ Menjalankan 'gradle wrapper' untuk membuat struktur wrapper lengkap..."
        (cd "$ANDROID_DIR" && gradle wrapper --gradle-version 8.4)

    # Opsi C: Unduh gradle-wrapper.jar resmi via curl
    elif command -v curl >/dev/null 2>&1; then
        echo "✅ Mengunduh gradle-wrapper.jar resmi via curl..."
        curl -fsSL https://raw.githubusercontent.com/gradle/gradle/v8.4.0/gradle/wrapper/gradle-wrapper.jar -o "$WRAPPER_JAR" || true

    # Opsi D: Unduh gradle-wrapper.jar via wget
    elif command -v wget >/dev/null 2>&1; then
        echo "✅ Mengunduh gradle-wrapper.jar via wget..."
        wget -q https://raw.githubusercontent.com/gradle/gradle/v8.4.0/gradle/wrapper/gradle-wrapper.jar -O "$WRAPPER_JAR" || true
    fi

    # Simpan kembali ke template jika berhasil didapatkan
    if [ -f "$WRAPPER_JAR" ] && [ -s "$WRAPPER_JAR" ]; then
        mkdir -p "$ROOT_DIR/scripts/android-templates"
        cp "$WRAPPER_JAR" "$TEMPLATE_JAR"
        echo "✅ File gradle-wrapper.jar berhasil disiapkan dan dicadangkan."
    fi
fi

# 6. Compile APK Debug menggunakan Gradle Wrapper atau Gradle sistem
echo "⚙️  Langkah 4/4: Kompilasi APK Android Debug..."

# Pastikan izin eksekusi gradlew aktif
if [ -f "$ANDROID_DIR/gradlew" ]; then
    chmod +x "$ANDROID_DIR/gradlew"
fi

# Pengecekan pra-kompilasi jika SDK belum ditemukan sama sekali
if [ ! -f "$LOCAL_PROPS" ] && [ -z "$ANDROID_HOME" ] && [ -z "$ANDROID_SDK_ROOT" ]; then
    echo ""
    echo "⚠️  PERINGATAN: Android SDK Location Belum Terpasang / Belum Dikonfigurasi."
    echo "Gradle membutuhkan lokasi Android SDK untuk mengompilasi APK."
    echo ""
    echo "Solusi Cepat (Pilih salah satu):"
    echo "1. Jika Anda memiliki Android Studio di Mac, jalankan perintah berikut di terminal:"
    echo "   echo \"sdk.dir=\$HOME/Library/Android/sdk\" > android/local.properties"
    echo "   lalu jalankan ulang ./build-apk.sh"
    echo ""
    echo "2. ATAU buka folder 'android' langsung di Android Studio:"
    echo "   File -> Open -> Pilih folder '${ANDROID_DIR}'"
    echo "   Android Studio akan mengonfigurasi SDK secara otomatis dan Anda cukup klik 'Build > Build APK'."
    echo ""
    exit 1
fi

if [ -f "$ANDROID_DIR/gradlew" ] && [ -f "$WRAPPER_JAR" ] && [ -s "$WRAPPER_JAR" ]; then
    echo "Menjalankan: ./gradlew assembleDebug di dalam direktori $ANDROID_DIR"
    (cd "$ANDROID_DIR" && ./gradlew assembleDebug)
elif command -v gradle >/dev/null 2>&1; then
    echo "Beralih menggunakan perintah 'gradle' sistem..."
    (cd "$ANDROID_DIR" && gradle assembleDebug)
else
    echo "⚠️  Catatan: gradlew atau gradle belum terpasang di path environment ini."
    echo "Semua file native Android, manifest, dan wrapper telah disiapkan dengan lengkap."
    echo "Anda dapat membuka folder 'android/' langsung menggunakan Android Studio untuk Build APK."
    exit 0
fi

APK_PATH="$ANDROID_DIR/app/build/outputs/apk/debug/app-debug.apk"

echo "=========================================================="
echo "🎉 KOMPILASI APK SELESAI!"
if [ -f "$APK_PATH" ]; then
    echo "File APK berhasil dibuat di:"
    echo "$APK_PATH"
else
    echo "Proses selesai. Periksa output Gradle di atas."
fi
echo "=========================================================="
